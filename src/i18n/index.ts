export function translate(lang: Lang, key: string): string {
  const e = D[key];
  if (!e) return key;
  return lang === 'he' ? e[0] : e[1];
}

export function useT() {
  const lang = useUI((s) => s.lang);
  return (key: string) => translate(lang, key);
}

export function speciesName(lang: Lang, sp: { hebrew_name: string; common_name: string }) {
  return lang === 'he' ? sp.hebrew_name || sp.common_name : sp.common_name || sp.hebrew_name;
}
