export function defaultLayers(): Layer[] {
  return LAYER_ORDER.map((id) => ({
    id,
    visible: id !== 'architectural_overlay',
    locked: id === 'background' || id === 'architectural_overlay',
    opacity: id === 'architectural_overlay' ? 0.6 : 1,
  }));
}

