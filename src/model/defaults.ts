export function layerForSpecies(sp: Species, height_m?: number): LayerId {
  const h = height_m ?? sp.default_height_m;
  if (sp.category === 'tree') return 'tree_canopies';
  if (sp.category === 'grass' || sp.category === 'groundcover' || sp.height_class === 'G0') return 'ground_cover';
  if (h > 1.8) return 'tall_shrubs';
  if (h > 1.0) return 'medium_shrubs';
  return 'low_vegetation';
}

